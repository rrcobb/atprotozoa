// Generate apex's lexicon registry from every site's published schemas.
//
// Each site that writes atproto records under net.bisks.* already serves its
// own schema at sites/<name>/public/lexicons/<nsid>.json (steamtags shipped
// the first one; see notes/ideas/pds-and-lexicons.md). Nothing aggregates
// them anywhere, so "is net.bisks.foo.bar documented" means grepping the
// whole repo. This script copies every schema into apex/public/lexicons/ and
// rebuilds an index page there, so https://bisks.net/lexicons/ is one place
// that lists every namespace, its record shape, and the site that owns it.
//
// Usage:
//   node audit/build-lexicons.mjs           # check: does apex match the sites?
//   node audit/build-lexicons.mjs --apply   # copy schemas + rewrite the index
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";

const APPLY = process.argv.includes("--apply");
const OUT_DIR = "apex/public/lexicons";
const INDEX = `${OUT_DIR}/index.html`;

const esc = (s) =>
  String(s).replace(/&(?!(?:amp|lt|gt|quot|#39);)/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");

const schemas = [];
for (const name of readdirSync("sites").sort()) {
  const dir = `sites/${name}/public/lexicons`;
  if (!existsSync(dir)) continue;
  const manifestPath = `sites/${name}/site.json`;
  const manifest = existsSync(manifestPath)
    ? JSON.parse(readFileSync(manifestPath, "utf8"))
    : null;
  for (const file of readdirSync(dir).sort()) {
    if (!file.startsWith("net.bisks.") || !file.endsWith(".json")) continue;
    const raw = readFileSync(`${dir}/${file}`, "utf8");
    const doc = JSON.parse(raw);
    schemas.push({
      id: doc.id,
      file,
      description: doc.defs?.main?.description || "",
      raw,
      site: name,
      siteTitle: manifest?.title || name,
      siteUrl: manifest?.url || `https://${name}.bisks.net/`,
    });
  }
}
schemas.sort((a, b) => a.id.localeCompare(b.id));

if (!APPLY) {
  console.log(`${schemas.length} schema(s) found across the repo:`);
  for (const s of schemas) console.log(`  ${s.id}  (${s.site})`);
  process.exit(0);
}

mkdirSync(OUT_DIR, { recursive: true });
for (const s of schemas) {
  writeFileSync(`${OUT_DIR}/${s.id}.json`, s.raw.endsWith("\n") ? s.raw : `${s.raw}\n`);
}

const rows = schemas
  .map(
    (s) => `        <a class="card" href="/lexicons/${esc(s.id)}.json">
          <h2>${esc(s.id)}</h2>
          <p>${esc(s.description)}</p>
          <p class="meta">written by <a href="${esc(s.siteUrl)}" onclick="event.stopPropagation()">${esc(s.siteTitle)}</a></p>
        </a>`
  )
  .join("\n");

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>net.bisks.* — lexicon registry — bisks.net</title>
    <meta name="description" content="Every net.bisks.* atproto record schema written by a bisks.net site, in one place." />
    <!-- generated by audit/build-lexicons.mjs --apply — don't hand-edit the
         card list, it gets overwritten from sites/*/public/lexicons/*.json -->
    <style>
      :root {
        --bg: #ffffff; --ink: #111111; --muted: #6b6b6b; --faint: #e4e4e4;
        --accent: #1a5fd0;
        --mono: ui-monospace, "SF Mono", "JetBrains Mono", "Cascadia Code",
          "Roboto Mono", Menlo, Consolas, monospace;
      }
      * { box-sizing: border-box; }
      body {
        margin: 0; background: var(--bg); color: var(--ink);
        font-family: var(--mono); font-size: 15px; line-height: 1.6;
        -webkit-font-smoothing: antialiased;
      }
      .wrap { max-width: 640px; margin: 0 auto; padding: 3.5rem 1.25rem 6rem; }
      header h1 { font-size: 1.6rem; margin: 0 0 0.35rem; font-weight: 600; }
      header p { color: var(--muted); margin: 0 0 1rem; font-size: 0.9rem; }
      header .count { color: var(--muted); font-size: 0.82rem; margin: 0 0 2.5rem; }
      .card {
        display: block; text-decoration: none; color: inherit;
        padding: 1.1rem 0; border-top: 1px solid var(--faint);
      }
      .card:first-of-type { border-top: 1px solid var(--ink); }
      .card:hover h2 { color: var(--accent); }
      .card h2 { font-size: 1.02rem; font-weight: 600; margin: 0 0 0.35rem; }
      .card p { margin: 0; color: var(--muted); font-size: 0.9rem; line-height: 1.6; }
      .card p.meta { margin-top: 0.35rem; font-size: 0.8rem; }
      .card p.meta a { color: var(--accent); text-decoration: none; }
      .card p.meta a:hover { text-decoration: underline; }
      footer {
        margin-top: 3rem; padding-top: 0.75rem; border-top: 1px solid var(--faint);
        color: var(--muted); font-size: 0.78rem;
      }
      footer a { color: var(--accent); text-decoration: none; }
      footer a:hover { text-decoration: underline; }
    </style>
  </head>
  <body>
    <div class="wrap">
      <header>
        <h1>net.bisks.*</h1>
        <p>every atproto record schema a bisks.net site writes, collected in one place.</p>
        <p class="count">${schemas.length} schemas across ${new Set(schemas.map((s) => s.site)).size} sites</p>
      </header>
      <main>
${rows}
      </main>
      <footer>
        <p>Each schema is copied verbatim from its owning site's own
        <code>/lexicons/&lt;nsid&gt;.json</code> — this page is a mirror, not the
        source of truth. NSID resolution (a <code>_lexicon</code> DNS TXT record)
        isn't wired up yet, so treat these as documentation you can fetch, not
        as resolvable lexicons. <a href="/">&larr; bisks.net</a></p>
      </footer>
    </div>
  </body>
</html>
`;

writeFileSync(INDEX, html);
console.log(`wrote ${schemas.length} schema(s) + index to ${OUT_DIR}/`);
