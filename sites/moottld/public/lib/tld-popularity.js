// TLDs we don't have a figure for fall back to this — small enough that an
// unrecognized TLD reads as "rare" (true for most obscure ccTLDs and vanity
// gTLDs not in the list above) without a near-zero denominator blowing the
// rarity score up to something absurd.
export const FALLBACK_COUNT = 5000;

export function globalCountFor(tld) {
  const key = String(tld || "").toLowerCase();
  return GLOBAL_TLD_COUNTS[key] || FALLBACK_COUNT;
}

// Re-rank a moottld tldList ([{tld, count}], sorted by raw mutual count) by
// rarity: each TLD's mutual count as a share of its *entire* global
// registration count. A TLD with a handful of mutuals but a tiny global
// footprint (say .moe) can outrank .com even though .com has 1000x the raw
// mutuals, because those 15 .com mutuals are a rounding error against 165
// million .com domains while a dozen .moe mutuals are a real slice of all
// .moe domains that exist.
export function rarityRank(tldList) {
  return tldList
    .map(({ tld, count }) => {
      const global = globalCountFor(tld);
      const known = Object.prototype.hasOwnProperty.call(GLOBAL_TLD_COUNTS, String(tld).toLowerCase());
      return { tld, count, global, share: count / global, estimated: !known };
    })
    .sort((a, b) => b.share - a.share || b.count - a.count);
}
