document.querySelectorAll('input[name="access"]').forEach((r) =>
  r.addEventListener("change", () => {
    document.getElementById("allowlist-wrap").style.display =
      document.querySelector('input[name="access"]:checked').value === "allowlist" ? "block" : "none";
  })
);

document.getElementById("genform").addEventListener("submit", (e) => {
  e.preventDefault();
  const c = readConfig();
  if (!c.handle || !c.owner) return;

  const fileList = files(c);
  const container = document.getElementById("files");
  container.innerHTML = "";

  for (const f of fileList) {
    const block = document.createElement("div");
    block.className = "file-block";
    block.innerHTML = `
      <div class="file-head">
        <h3>${esc(f.name)}</h3>
        <div class="btns">
          <button class="ghost" type="button" data-copy>copy</button>
          <button class="ghost" type="button" data-dl>download</button>
        </div>
      </div>
      <pre><code>${esc(f.content)}</code></pre>
    `;
    block.querySelector("[data-copy]").addEventListener("click", () => {
      navigator.clipboard.writeText(f.content);
    });
    block.querySelector("[data-dl]").addEventListener("click", () => download(f.name, f.content));
    container.appendChild(block);
  }

  document.getElementById("output").classList.add("ready");
  document.getElementById("download-install").onclick = () =>
    download("install.sh", buildInstallScript(fileList, c));

  document.getElementById("output").scrollIntoView({ behavior: "smooth", block: "start" });
});
