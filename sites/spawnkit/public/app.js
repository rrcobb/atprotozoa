function download(filename, content) {
  const blob = new Blob([content], { type: "text/plain" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function buildInstallScript(fileList, c) {
  const parts = [
    "#!/usr/bin/env bash",
    "# generated by spawnkit.bisks.net — writes every file for a spawnkit bot",
    "# into ./spawnkit-bot/, ready to configure and run.",
    "set -euo pipefail",
    'mkdir -p spawnkit-bot && cd spawnkit-bot',
    "",
  ];
  for (const f of fileList) {
    const delim = "SPAWNKIT_EOF_" + f.name.replace(/[^A-Za-z0-9]/g, "_").toUpperCase();
    parts.push(`cat > ${JSON.stringify(f.name)} <<'${delim}'`);
    parts.push(f.content.replace(/\r/g, ""));
    parts.push(delim);
    parts.push("");
  }
  parts.push('chmod +x build-loop.sh watcher.mjs reply.mjs 2>/dev/null || true');
  parts.push('echo "wrote $(ls | wc -l) files to $(pwd) — read README.md next"');
  return parts.join("\n");
}

