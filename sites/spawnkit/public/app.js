function esc(s) {
  return String(s).replace(/[&<>]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" }[c]));
}

function readConfig() {
  const handle = document.getElementById("handle").value.trim().replace(/^@/, "");
  const owner = document.getElementById("owner").value.trim().replace(/^@/, "");
  const access = document.querySelector('input[name="access"]:checked').value;
  const allowlist = document
    .getElementById("allowlist")
    .value.split(",")
    .map((s) => s.trim().replace(/^@/, ""))
    .filter(Boolean);
  const purpose = document.getElementById("purpose").value.trim() || "small, self-contained web toys";
  const workdir = document.getElementById("workdir").value.trim() || "./work";
  const agentcmd = document.getElementById("agentcmd").value.trim() || "claude -p";
  return { handle, owner, access, allowlist, purpose, workdir, agentcmd };
}

