function tplReadme(c) {
  const accessLine = {
    owner: `Only **@${c.owner}** can trigger a build.`,
    mutuals: `**@${c.owner}** and anyone who mutually follows them on Bluesky can trigger a build.`,
    allowlist: `Only these handles can trigger a build: ${c.allowlist.length ? c.allowlist.map((h) => "@" + h).join(", ") : "(none set — edit ALLOWLIST in .env)"}.`,
    public: `Anyone can trigger a build (rate-limited per account — see watcher.mjs). Think hard before running this mode unattended.`,
  }[c.access];

  return `# @${c.handle} — a spawnkit bot

Generated by spawnkit (spawnkit.bisks.net) for **@${c.owner}**. This is a
starter kit, not a finished product — six small files that do the minimum
version of "tag it, get a site": a watcher, a build loop, a prompt template,
and a reply script. Read this whole file before running anything.

## What it does

1. \`watcher.mjs\` connects to Bluesky's firehose (via Jetstream) and watches
   for posts that mention \`@${c.handle}\`.
2. It checks whether the poster is allowed to trigger a build. Your rule:
   ${accessLine}
3. Allowed mentions get written to \`jobs/\` as a small JSON file.
4. \`build-loop.sh\` polls \`jobs/\`, picks up the oldest one, and runs your
   coding agent (\`${c.agentcmd}\`) against \`BUILD_PROMPT.md\` with the
   request filled in.
5. \`reply.mjs\` posts a reply on the original thread with what happened.

Nothing here is serverless — the coding agent needs a real, persistent
process with a shell and a filesystem, so this whole kit assumes a machine
you control (a VPS, a spare box, a container), running for as long as the
bot should be up.

## Setup

1. **Make the bot account.** Create (or repurpose) a Bluesky account for
   \`@${c.handle}\`, then generate an
   [app password](https://bsky.app/settings/app-passwords) for it — never
   use the account's real password here.

2. **Install dependencies.** This kit is plain Node (18.17+, for built-in
   \`fetch\`/\`WebSocket\`) and bash. No build step.

3. **Copy \`.env.example\` to \`.env\`** and fill it in:
   - \`BOT_HANDLE\`, \`BOT_APP_PASSWORD\` — the account from step 1.
   - \`OWNER_HANDLE\` — you, \`@${c.owner}\`.
   - \`ACCESS_MODE\` — \`${c.access}\` (change any time; see watcher.mjs).
   - \`ALLOWLIST\` — only used in \`allowlist\` mode.
   - \`WORKDIR\` — \`${c.workdir}\`, where your agent is allowed to write.
     Make this its own git repo (or scratch directory) — **not** a checkout
     of anything you care about, until you trust what the agent does there.
   - \`AGENT_CMD\` — \`${c.agentcmd}\`. Whatever you run must read a prompt
     (piped on stdin) and be able to edit files under \`WORKDIR\` unattended.

4. **Run the watcher and the build loop as two long-lived processes:**

   \`\`\`sh
   node watcher.mjs &
   bash build-loop.sh &
   \`\`\`

   In production, wrap both in systemd units (or your process manager of
   choice) so they restart on crash/reboot. This kit doesn't include a unit
   file — copy one from any always-on service you already run.

5. **Tag it.** Post on Bluesky mentioning \`@${c.handle}\` from an allowed
   account and watch \`jobs/\` — a file should appear, then get picked up
   and moved to \`jobs/done/\`.

## What spawnkit deliberately left out

- **Deploying the result anywhere.** \`BUILD_PROMPT.md\` tells the agent
  where to write files (\`WORKDIR\`); what happens after that — commit and
  push, a static host, nothing at all — is up to you and your agent's own
  instructions.
- **A real job queue.** \`jobs/\` is a directory of JSON files, checked by
  \`ls\` order. Fine for one person's bot; replace it if you expect real
  concurrency or need retries/backoff.
- **Rate limiting beyond the crude per-account cooldown in watcher.mjs.**
  If you pick \`public\` access mode, add more before you actually open it
  up — an unattended coding agent triggered by strangers is a real
  responsibility.
- **Sandboxing the agent.** This kit assumes you trust whatever \`AGENT_CMD\`
  does inside \`WORKDIR\`. It runs with no isolation beyond what you add
  yourself (container, restricted user, filesystem jail — your call).

## Files in this kit

- \`.env.example\` — copy to \`.env\`, fill in.
- \`watcher.mjs\` — Jetstream listener + access check + job writer.
- \`build-loop.sh\` — polls \`jobs/\`, runs the agent, calls \`reply.mjs\`.
- \`BUILD_PROMPT.md\` — the prompt template handed to your agent.
- \`reply.mjs\` — posts the reply back to Bluesky.

Generated by [spawnkit.bisks.net](https://spawnkit.bisks.net/), inspired by
[@buildthis.bisks.net](https://buildthis.bisks.net/). Not affiliated, not a
copy — just the same shape.
`;
}

